  private Disease build(String name, String type, String desc,
                        String regions, String species, String causes,
                        String symptoms, String treatment, String prevention,
                        String temp, String imageUrl) {
    Disease d = new Disease();
    d.setName(name);
    d.setDiseaseType(type);
    d.setDescription(desc);
    d.setPrevalentRegions(regions);
    d.setAffectedSpecies(species);
    d.setCauses(causes);
    d.setSymptomsSummary(symptoms);
    d.setTreatment(treatment);
    d.setPrevention(prevention);
    d.setPrevalentTemp(temp);
    d.setImageUrl(imageUrl);
    return d;
  }
